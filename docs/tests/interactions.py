"""Interaction tests for v2 features (run with the site served on :8765)."""
import asyncio
from playwright.async_api import async_playwright
STUB = open('/tmp/stub.jpg', 'rb').read()
async def main():
    res = []
    ok = lambda name, cond: res.append(('PASS' if cond else 'FAIL') + '  ' + name)
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome')
        pg = await b.new_page(viewport={'width': 1440, 'height': 900})
        await pg.route('https://i.ytimg.com/**', lambda r: r.fulfill(body=STUB, content_type='image/jpeg'))
        await pg.route('https://www.youtube-nocookie.com/**', lambda r: r.fulfill(body='<html>video</html>', content_type='text/html'))
        await pg.goto('http://localhost:8765/about.html'); await pg.wait_for_timeout(300)
        ok('slideshow: first slide visible', await pg.evaluate("document.querySelector('.slide.on')===document.querySelectorAll('.slide')[0]"))
        await pg.click('[data-slide-next]'); await pg.wait_for_timeout(100)
        ok('slideshow: next moves to slide 2', await pg.evaluate("document.querySelectorAll('.slide')[1].classList.contains('on')"))
        ok('slideshow: caption updates', 'Second Service' in (await pg.inner_text('[data-slide-cap]')) or len(await pg.inner_text('[data-slide-cap]')) > 5)
        await pg.click('[data-slide-pause]')
        ok('slideshow: pause toggles', await pg.get_attribute('[data-slide-pause]', 'aria-pressed') == 'true')
        await pg.click('#family [data-lightbox] >> nth=0'); await pg.wait_for_timeout(200)
        ok('lightbox: opens with video iframe', await pg.evaluate("document.getElementById('lightbox').open && !!document.querySelector('#lb-frame iframe')"))
        await pg.keyboard.press('ArrowRight'); await pg.wait_for_timeout(100)
        ok('lightbox: arrow key advances', 'nocookie' in (await pg.evaluate("document.querySelector('#lb-frame iframe').src")))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(100)
        ok('lightbox: Esc closes and clears video', await pg.evaluate("!document.getElementById('lightbox').open && !document.querySelector('#lb-frame iframe')"))
        await pg.goto('http://localhost:8765/conference.html'); await pg.wait_for_timeout(300)
        sl0 = await pg.evaluate("document.getElementById('rail-c26').scrollLeft")
        await pg.click('[data-rail=rail-c26][data-dir="1"]'); await pg.wait_for_timeout(700)
        ok('rail: arrow scrolls row', await pg.evaluate("document.getElementById('rail-c26').scrollLeft") > sl0)
        ok('countdown: shows days', 'days' in (await pg.inner_text('[data-countdown]')).lower())
        await pg.goto('http://localhost:8765/sermons.html'); await pg.wait_for_timeout(300)
        await pg.click('[data-filter=praise]')
        vis = await pg.evaluate("[...document.querySelectorAll('#library .video')].filter(v=>!v.hidden).map(v=>v.dataset.cat)")
        ok('sermons: category filter', len(vis) > 0 and set(vis) == {'praise'})
        await pg.click('[data-filter=all]'); await pg.select_option('#speaker', 'Rev. Gabriel Ngugi')
        vis = await pg.evaluate("[...document.querySelectorAll('#library .video')].filter(v=>!v.hidden).map(v=>v.dataset.speaker)")
        ok('sermons: speaker filter', len(vis) > 0 and set(vis) == {'Rev. Gabriel Ngugi'})
        await pg.click('#library .video:not([hidden]) button.play >> nth=0'); await pg.wait_for_timeout(200)
        ok('video: lite embed loads nocookie iframe on click', await pg.evaluate("!!document.querySelector('#library iframe[src*=nocookie]')"))
        await pg.goto('http://localhost:8765/events.html'); await pg.wait_for_timeout(300)
        await pg.click('[data-efilter=Leadership]')
        vis = await pg.evaluate("[...document.querySelectorAll('#past .ecard')].filter(v=>!v.hidden).map(v=>v.dataset.cat)")
        ok('events: past filter', len(vis) > 0 and set(vis) == {'Leadership'})
        ok('events: no past event shown as upcoming', await pg.evaluate("![...document.querySelectorAll('.feature-event h2')].some(h=>/2026|2025|2024/.test(h.textContent))"))
        await pg.goto('http://localhost:8765/visit.html'); await pg.wait_for_timeout(200)
        await pg.click('[data-map-load]'); await pg.wait_for_timeout(200)
        ok('visit: map loads only on click', await pg.evaluate("!!document.querySelector('[data-map] iframe')"))
        await pg.click('#enquiry button[type=submit]')
        ok('visit form: validation message', 'highlighted' in await pg.inner_text('#enquiry .form-status'))
        await pg.goto('http://localhost:8765/gallery.html'); await pg.wait_for_timeout(200)
        await pg.click('[data-gfilter="Conferences"]')
        vis = await pg.evaluate("[...document.querySelectorAll('.collage figure')].filter(v=>!v.hidden).map(v=>v.dataset.cat)")
        ok('gallery: category filter', len(vis) > 0 and set(vis) == {'Conferences'})
        m = await b.new_page(viewport={'width': 390, 'height': 780})
        await m.goto('http://localhost:8765/about.html'); await m.wait_for_timeout(200)
        await m.click('.menu-toggle'); await m.wait_for_timeout(250)
        ok('mobile: menu opens', await m.get_attribute('.menu-toggle', 'aria-expanded') == 'true')
        await m.keyboard.press('Escape')
        ok('mobile: Esc closes menu', await m.get_attribute('.menu-toggle', 'aria-expanded') == 'false')
        rm = await b.new_page(viewport={'width': 1024, 'height': 800}, reduced_motion='reduce')
        await rm.goto('http://localhost:8765/about.html'); await rm.wait_for_timeout(200)
        ok('reduced motion: slideshow starts paused', await rm.get_attribute('[data-slide-pause]', 'aria-pressed') == 'true')

        # ---- v2.1 photography & motion layer
        await pg.goto('http://localhost:8765/index.html'); await pg.wait_for_timeout(600)
        ok('hero: photo present and loaded', await pg.evaluate("(()=>{const i=document.querySelector('.hx-photo img');return !!i && i.complete && i.naturalWidth>0})()"))
        ok('hero: fallback background defined', 'url(' in await pg.evaluate("getComputedStyle(document.querySelector('.hx-photo')).backgroundImage"))
        await pg.route('https://i.ytimg.com/vi/GOjZxrPfljE/**', lambda r: r.abort())
        await pg.goto('http://localhost:8765/index.html'); await pg.wait_for_timeout(800)
        ok('hero: failed photo is hidden, never a broken icon', await pg.evaluate("document.querySelector('.hx-photo img').classList.contains('img-failed')"))
        await pg.unroute('https://i.ytimg.com/vi/GOjZxrPfljE/**')
        await pg.goto('http://localhost:8765/gallery.html'); await pg.wait_for_timeout(500)
        x0 = await pg.evaluate("document.querySelector('.xrail').scrollLeft")
        await pg.click('[data-strip=next]'); await pg.wait_for_timeout(800)
        ok('film strip: arrow scrolls', await pg.evaluate("document.querySelector('.xrail').scrollLeft") > x0)
        await pg.click('.xrail [data-lb] >> nth=0'); await pg.wait_for_timeout(300)
        ok('photo viewer: opens full screen', await pg.evaluate("document.querySelector('dialog.lb').open && !!document.querySelector('dialog.lb img').src"))
        c1 = await pg.inner_text('.lb-count'); await pg.keyboard.press('ArrowRight'); await pg.wait_for_timeout(150)
        ok('photo viewer: arrow key advances', (await pg.inner_text('.lb-count')) != c1)
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(150)
        ok('photo viewer: Esc closes and returns focus', await pg.evaluate("!document.querySelector('dialog.lb').open && document.activeElement.hasAttribute('data-lb')"))
        ok('nav: Gallery link present on every page', await pg.evaluate("!!document.querySelector('.nav a[href=\"gallery.html\"]')"))
        await b.close()
    print('\n'.join(res)); open('tests/interaction-results.txt', 'w').write('\n'.join(res) + '\n')
asyncio.run(main())
